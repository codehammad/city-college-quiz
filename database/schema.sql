CREATE DATABASE IF NOT EXISTS city_college_quiz CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE city_college_quiz;

CREATE TABLE IF NOT EXISTS admins (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, full_name VARCHAR(120) NOT NULL, profile_photo VARCHAR(255) NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS campuses (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE,
 location VARCHAR(160) NOT NULL, is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS teams (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, campus_id INT UNSIGNED NOT NULL,
 team_name VARCHAR(100) NOT NULL, username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, profile_photo VARCHAR(255) NULL, is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY uq_one_team_per_campus (campus_id),
 CONSTRAINT fk_team_campus FOREIGN KEY (campus_id) REFERENCES campuses(id)
);
CREATE TABLE IF NOT EXISTS competitions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(160) NOT NULL,
 description TEXT, category VARCHAR(80) NOT NULL, start_at DATETIME NOT NULL,
 duration_minutes SMALLINT UNSIGNED NOT NULL, marks_per_question TINYINT UNSIGNED NOT NULL DEFAULT 1,
 status ENUM('Draft','Scheduled','Live','Completed') NOT NULL DEFAULT 'Draft',
 results_release ENUM('immediate','after_competition') NOT NULL DEFAULT 'immediate',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_competition_status_start (status,start_at)
);
CREATE TABLE IF NOT EXISTS competition_teams (
 competition_id INT UNSIGNED NOT NULL, team_id INT UNSIGNED NOT NULL,
 PRIMARY KEY (competition_id,team_id),
 FOREIGN KEY (competition_id) REFERENCES competitions(id) ON DELETE CASCADE,
 FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS questions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, competition_id INT UNSIGNED NOT NULL,
 question_text TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (competition_id) REFERENCES competitions(id) ON DELETE CASCADE,
 INDEX idx_question_competition (competition_id)
);
CREATE TABLE IF NOT EXISTS options (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, question_id INT UNSIGNED NOT NULL,
 option_text VARCHAR(500) NOT NULL, is_correct BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY (question_id) REFERENCES questions(id) ON DELETE CASCADE,
 INDEX idx_option_question (question_id)
);
CREATE TABLE IF NOT EXISTS quiz_attempts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, competition_id INT UNSIGNED NOT NULL,
 team_id INT UNSIGNED NOT NULL, started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 submitted_at DATETIME NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_attempt (competition_id,team_id),
 FOREIGN KEY (competition_id) REFERENCES competitions(id) ON DELETE CASCADE,
 FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS team_answers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, attempt_id INT UNSIGNED NOT NULL,
 question_id INT UNSIGNED NOT NULL, option_id INT UNSIGNED NOT NULL,
 answered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_attempt_question (attempt_id,question_id),
 FOREIGN KEY (attempt_id) REFERENCES quiz_attempts(id) ON DELETE CASCADE,
 FOREIGN KEY (question_id) REFERENCES questions(id) ON DELETE CASCADE,
 FOREIGN KEY (option_id) REFERENCES options(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS results (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, attempt_id INT UNSIGNED NOT NULL UNIQUE,
 competition_id INT UNSIGNED NOT NULL, team_id INT UNSIGNED NOT NULL,
 score INT UNSIGNED NOT NULL DEFAULT 0, correct_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 submitted_at DATETIME NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (attempt_id) REFERENCES quiz_attempts(id) ON DELETE CASCADE,
 FOREIGN KEY (competition_id) REFERENCES competitions(id) ON DELETE CASCADE,
 FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE CASCADE,
 INDEX idx_results_rank (competition_id,score,submitted_at)
);
